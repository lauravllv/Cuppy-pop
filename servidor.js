const { randomUUID } = require("crypto");
const { Pool } = require("pg");
const { MercadoPagoConfig, Preference, Payment } = require("mercadopago");

const app = express();
const PORT = process.env.PORT || 3000;
const APP_URL = (process.env.APP_URL || `http://localhost:${PORT}`).replace(/\/+$/, "");
const MODO_MP = (process.env.MP_ENV || "pruebas").toLowerCase();

app.use(express.json());

const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false }
});

pool.on("error", error => {
    console.error("Error inesperado de PostgreSQL:", error.message);
});

const PRECIOS = {
    "Galleta": 15,
    "Cupcake de vainilla": 10,
    "Cupcake de chocolate": 10,
    "Pan": 30,
    "Croissant": 25
};

// Crea las tablas solamente si no existen y agrega
// las columnas opcionales que utiliza el sistema.
async function inicializarBD() {
    if (!process.env.DATABASE_URL) {
        throw new Error("Falta configurar DATABASE_URL en Render.");
    }

    await pool.query(`
        CREATE TABLE IF NOT EXISTS pedidos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nombre TEXT NOT NULL,
            telefono TEXT NOT NULL,
            direccion TEXT NOT NULL,
            indicaciones TEXT,
            productos JSONB NOT NULL,
            total NUMERIC(10,2) NOT NULL,
            metodo_pago TEXT NOT NULL,
            estado_pedido TEXT NOT NULL DEFAULT 'recibido',
            estado_pago TEXT NOT NULL DEFAULT 'pendiente',
            fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            referencia_transferencia TEXT,
            mp_payment_id TEXT,
            mp_external_reference TEXT
        )
    `);

    await pool.query(`
        CREATE TABLE IF NOT EXISTS checkout_pendientes (
            referencia TEXT PRIMARY KEY,
            nombre TEXT NOT NULL,
            telefono TEXT NOT NULL,
            direccion TEXT NOT NULL,
            indicaciones TEXT,
            productos JSONB NOT NULL,
            total NUMERIC(10,2) NOT NULL,
            preferencia_id TEXT,
            creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    `);

    await pool.query(`
        ALTER TABLE pedidos
        ADD COLUMN IF NOT EXISTS referencia_transferencia TEXT,
        ADD COLUMN IF NOT EXISTS mp_payment_id TEXT,
        ADD COLUMN IF NOT EXISTS mp_external_reference TEXT
    `);

    console.log("Base de datos Supabase preparada.");
}

function clienteMP() {
    const token = process.env.MP_ACCESS_TOKEN;

    if (!token) {
        throw new Error("Falta MP_ACCESS_TOKEN en las variables de entorno.");
    }

    if (MODO_MP === "produccion" && !token.startsWith("APP_USR-")) {
        throw new Error("Verifica las credenciales de producción de Mercado Pago.");
    }

    if (!["pruebas", "produccion"].includes(MODO_MP)) {
        throw new Error("MP_ENV debe ser pruebas o produccion.");
    }

    return new MercadoPagoConfig({ accessToken: token });
}

function validarProductos(items) {
    if (!Array.isArray(items) || items.length === 0) {
        throw new Error("El carrito está vacío.");
    }

    let total = 0;

    const lista = items.map(item => {
        const precio = PRECIOS[item.nombre];

        if (
            !precio ||
            !Number.isInteger(item.cantidad) ||
            item.cantidad < 1 ||
            item.cantidad > 50
        ) {
            throw new Error("Producto o cantidad no válidos.");
        }

        total += precio * item.cantidad;

        return {
            nombre: item.nombre,
            cantidad: item.cantidad,
            precio
        };
    });

    return { lista, total };
}

function validarCliente({ nombre, telefono, direccion }) {
    if (
        typeof nombre !== "string" || !nombre.trim() ||
        typeof telefono !== "string" || !telefono.trim() ||
        typeof direccion !== "string" || !direccion.trim()
    ) {
        throw new Error("Completa nombre, teléfono y dirección.");
    }
}

