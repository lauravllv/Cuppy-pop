// TRANSFERENCIA BBVA.
app.post("/api/pedidos", async (req, res) => {
    try {
        const {
            nombre,
            telefono,
            direccion,
            indicaciones = "",
            productos,
            metodo_pago,
            referencia_transferencia = ""
        } = req.body;

        if (metodo_pago !== "transferencia") {
            return res.status(400).json({
                error: "Esta ruta solo registra pedidos por transferencia."
            });
        }

        validarCliente({ nombre, telefono, direccion });

        const { lista, total } = validarProductos(productos);

        const resultado = await pool.query(`
            INSERT INTO pedidos (
                nombre, telefono, direccion, indicaciones,
                productos, total, metodo_pago,
                estado_pedido, estado_pago, referencia_transferencia
            )
            VALUES (
                $1, $2, $3, $4, $5::jsonb, $6,
                'transferencia', 'recibido',
                'pendiente_revision', $7
            )
            RETURNING id
        `, [
            nombre.trim(),
            telefono.trim(),
            direccion.trim(),
            String(indicaciones || ""),
            JSON.stringify(lista),
            total,
            String(referencia_transferencia || "").trim()
        ]);

        res.status(201).json({
            pedidoId: Number(resultado.rows[0].id),
            total,
            estadoPago: "pendiente_revision"
        });
    } catch (error) {
        console.error("Error en transferencia:", error.message);

        res.status(400).json({
            error: error.message || "No se pudo registrar el pedido."
        });
    }
});

// MERCADO PAGO: crea un checkout pendiente.
app.post("/api/crear-pago", async (req, res) => {
    let referencia;

    try {
        const {
            nombre,
            telefono,
            direccion,
            indicaciones = "",
            items
        } = req.body;

        validarCliente({ nombre, telefono, direccion });

        const { lista, total } = validarProductos(items);

        referencia = randomUUID();

        await pool.query(`
            INSERT INTO checkout_pendientes (
                referencia, nombre, telefono, direccion,
                indicaciones, productos, total
            )
            VALUES ($1, $2, $3, $4, $5, $6::jsonb, $7)
        `, [
            referencia,
            nombre.trim(),
            telefono.trim(),
            direccion.trim(),
            String(indicaciones || ""),
            JSON.stringify(lista),
            total
        ]);

        const preference = new Preference(clienteMP());

        const resultado = await preference.create({
            body: {
                items: lista.map(producto => ({
                    title: producto.nombre,
                    quantity: producto.cantidad,
                    unit_price: producto.precio,
                    currency_id: "MXN"
                })),
                external_reference: referencia,
                back_urls: {
                    success: `${APP_URL}/pago/resultado`,
                    pending: `${APP_URL}/pago/resultado`,
                    failure: `${APP_URL}/pago/resultado`
                },
                auto_return: "approved"
            }
        });

        await pool.query(`
            UPDATE checkout_pendientes
            SET preferencia_id = $1
            WHERE referencia = $2
        `, [String(resultado.id), referencia]);

        const url = resultado.init_point;

        if (!url) {
            throw new Error(
                "Mercado Pago no devolvió el enlace de pago. Verifica tus credenciales y el entorno."
            );
        }

        res.status(201).json({ url });
    } catch (error) {
        console.error("Error al crear checkout:", error.message);

        if (referencia) {
            try {
                await pool.query(
                    "DELETE FROM checkout_pendientes WHERE referencia = $1",
                    [referencia]
                );
            } catch (errorBD) {
                console.error("No se pudo limpiar el checkout:", errorBD.message);
            }
        }

        res.status(500).json({
            error: error.message || "No se pudo crear el checkout."
        });
    }
});

// Verifica el pago directamente con Mercado Pago.
// Solo registra el pedido cuando el pago está aprobado.
async function procesarPagoVerificado(paymentId) {
    const payment = await new Payment(clienteMP()).get({ id: paymentId });

    if (payment.status !== "approved") {
        return {
            estado: payment.status || "desconocido",
            guardado: false
        };
    }

    const referencia = String(payment.external_reference || "");

    if (!referencia) {
        throw new Error("El pago no tiene referencia externa.");
    }

    const client = await pool.connect();
    let transaccionIniciada = false;

    try {
        await client.query("BEGIN");
        transaccionIniciada = true;

        const consultaCheckout = await client.query(`
            SELECT *
            FROM checkout_pendientes
            WHERE referencia = $1
            FOR UPDATE
        `, [referencia]);

        const checkout = consultaCheckout.rows[0];

        if (!checkout) {
            const existente = await client.query(`
                SELECT id
                FROM pedidos
                WHERE mp_payment_id = $1
                LIMIT 1
            `, [String(paymentId)]);

            if (existente.rows.length > 0) {
                await client.query("COMMIT");
                transaccionIniciada = false;

                return {
                    estado: "approved",
                    guardado: true,
                    pedidoId: Number(existente.rows[0].id)
                };
            }

            throw new Error("No se encontró el checkout asociado al pago.");
        }

        if (
            payment.currency_id !== "MXN" ||
            Math.abs(
                Number(payment.transaction_amount) - Number(checkout.total)
            ) > 0.01
        ) {
            throw new Error("El importe o la moneda no coinciden con el pedido.");
        }

        const resultado = await client.query(`
            INSERT INTO pedidos (
                nombre, telefono, direccion, indicaciones,
                productos, total, metodo_pago, estado_pedido,
                estado_pago, mp_payment_id, mp_external_reference
            )
            VALUES (
                $1, $2, $3, $4, $5::jsonb, $6,
                'mercadopago', 'recibido', 'aprobado', $7, $8
            )
            RETURNING id
        `, [
            checkout.nombre,
            checkout.telefono,
            checkout.direccion,
            checkout.indicaciones || "",
            JSON.stringify(checkout.productos),
            Number(checkout.total),
            String(paymentId),
            referencia
        ]);

        await client.query(`
            DELETE FROM checkout_pendientes
            WHERE referencia = $1
        `, [referencia]);

        await client.query("COMMIT");
        transaccionIniciada = false;

        return {
            estado: "approved",
            guardado: true,
            pedidoId: Number(resultado.rows[0].id)
        };
    } catch (error) {
        if (transaccionIniciada) {
            await client.query("ROLLBACK");
        }

        throw error;
    } finally {
        client.release();
    }
}

app.get("/api/verificar-pago/:id", async (req, res) => {
    try {
        if (!/^\d+$/.test(req.params.id)) {
            return res.status(400).json({
                error: "ID de pago no válido."
            });
        }

        res.json(await procesarPagoVerificado(req.params.id));
    } catch (error) {
        console.error("Error al verificar pago:", error.message);

        res.status(500).json({
            error: "No se pudo verificar el pago."
        });
    }
});

